import { PDFDocument, rgb } from 'pdf-lib'
import { writeFileSync } from 'fs'

// Create a minimal valid PNG (2x2 blue pixel)
const pngBytes = Buffer.from([
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
  0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x02,
  0x08, 0x02, 0x00, 0x00, 0x00, 0xFD, 0xD4, 0x9A, 0x73,
  0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41, 0x54,
  0x08, 0xD7, 0x63, 0xF8, 0x4F, 0xC0, 0x00, 0x00,
  0x00, 0x03, 0x00, 0x01, 0x5C, 0xCD, 0xFF, 0x69,
  0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44,
  0xAE, 0x42, 0x60, 0x82
])

const doc = await PDFDocument.create()
const pngImg = await doc.embedPng(pngBytes)

// Image-only page — NO text at all
const page = doc.addPage([595, 842])
page.drawImage(pngImg, { x: 100, y: 300, width: 400, height: 400 })

writeFileSync('test-pdfs/pdf-image-only.pdf', await doc.save())
console.log('Created pdf-image-only.pdf (1 page, image only, no text)')
